-- ═══════════════════════════════════════════════════════════════
--  V6 — 제품 누끼 이미지
--
--  메인의 회전 원판 연출에 쓰는 배경 제거(누끼) 사진.
--
--  ── 왜 thumbnail_key 를 재사용하지 않는가 ──
--
--  용도가 다르다. 썸네일은 목록 카드에 들어가는 "상황이 있는 사진"이고,
--  누끼는 배경 없이 기구만 떠 있어야 하는 "전시용 사진"이다.
--  카드에 누끼를 쓰면 허전하고, 원판에 배경 있는 사진을 올리면
--  검은 바닥 위에 흰 네모가 떠다닌다.
--
--  ── 왜 product_image 에 role 을 넣지 않는가 ──
--
--  누끼는 제품당 정확히 하나다. role 컬럼을 두면 "누끼가 세 장인 제품"이
--  만들어질 수 있고, 그때 원판이 무엇을 고를지 규칙이 또 필요해진다.
--  하나만 가질 수 있게 컬럼으로 못박는다.
--
--  ── 투명도 ──
--
--  업로드 파이프라인이 알파 채널이 있으면 PNG 로 재인코딩하므로
--  누끼의 투명 배경은 그대로 보존된다. 별도 처리가 필요 없다.
-- ═══════════════════════════════════════════════════════════════

ALTER TABLE product
    ADD COLUMN cutout_key VARCHAR(255);

COMMENT ON COLUMN product.cutout_key IS
    '배경 제거(누끼) 사진의 스토리지 키. 메인 회전 원판에 쓴다. NULL 이면 설치 면적 다이어그램으로 대체된다.';

-- 원판은 "누끼가 있고 공개 상태인 기구"만 골라 온다.
-- 부분 인덱스라 누끼 없는 제품 행은 인덱스에 들어가지 않는다.
CREATE INDEX ix_product_cutout
    ON product (sort_order, id)
    WHERE visible AND cutout_key IS NOT NULL;
