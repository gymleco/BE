-- ═══════════════════════════════════════════════════════════════
--  V4 — 문의에 공간 정보 추가
--
--  메인 CTA 가 "평수와 천장 높이만 알려주셔도 충분합니다" 라고
--  약속한다. FE 폼과 프록시는 이미 spaceInfo 를 보내고 있었는데
--  받는 컬럼이 없어 유실되고 있었다.
--
--  자유 입력("30평 / 2.6m")이며 개인정보가 아니다 — 암호화 대상이
--  아니고, inquiry 행과 함께 purge 배치로 파기된다.
-- ═══════════════════════════════════════════════════════════════

ALTER TABLE inquiry
    ADD COLUMN space_info VARCHAR(200);

COMMENT ON COLUMN inquiry.space_info IS
    '평수·천장고 등 공간 조건 자유 입력. 배치안 회신의 입력값.';
