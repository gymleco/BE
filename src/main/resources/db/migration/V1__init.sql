-- ───────────────────────────────────────────────────────────────
--  관리자 계정
-- ───────────────────────────────────────────────────────────────
CREATE TABLE admin_user (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(60)  NOT NULL,
    -- ★ BCrypt 해시만. 평문·MD5·SHA 금지 (기획서 §10).
    --   MD5 는 GPU 로 초당 수십억 건 대입이 가능해 사실상 평문과 같다.
    password_hash   VARCHAR(100) NOT NULL,
    display_name    VARCHAR(60)  NOT NULL DEFAULT '',
    role            VARCHAR(20)  NOT NULL DEFAULT 'ADMIN',
    enabled         BOOLEAN      NOT NULL DEFAULT TRUE,

    -- TOTP 2FA. 시크릿은 암호화해서 저장한다.
    totp_secret_encrypted TEXT,
    totp_enabled    BOOLEAN      NOT NULL DEFAULT FALSE,

    last_login_at   TIMESTAMPTZ,
    last_login_ip   INET,
    password_changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_admin_user_username UNIQUE (username),
    CONSTRAINT ck_admin_user_role     CHECK (role IN ('ADMIN', 'EDITOR')),
    -- BCrypt 해시는 항상 $2a$/$2b$/$2y$ 로 시작한다.
    -- 다른 알고리즘이 섞여 들어오면 DB 가 거부한다.
    CONSTRAINT ck_admin_user_bcrypt   CHECK (password_hash ~ '^\$2[aby]\$')
);


-- Refresh Token 은 DB 에 두고 로그아웃 시 무효화한다 (기획서 §10).
-- 토큰 자체가 아니라 해시를 저장한다 — DB 유출만으로 세션을 탈취당하지
-- 않게 하기 위해서다.
CREATE TABLE admin_refresh_token (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_user_id BIGINT       NOT NULL,
    token_hash    BYTEA        NOT NULL,
    issued_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expires_at    TIMESTAMPTZ  NOT NULL,
    revoked_at    TIMESTAMPTZ,
    -- 재사용 감지: 이미 회전된 토큰이 다시 오면 탈취로 간주하고
    -- 해당 사용자의 모든 세션을 끊는다.
    replaced_by   BIGINT,
    user_agent    VARCHAR(400),
    ip            INET,

    CONSTRAINT uq_admin_refresh_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_admin_refresh_token_user
        FOREIGN KEY (admin_user_id) REFERENCES admin_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_admin_refresh_token_replaced
        FOREIGN KEY (replaced_by) REFERENCES admin_refresh_token (id) ON DELETE SET NULL
);

CREATE INDEX ix_admin_refresh_token_user    ON admin_refresh_token (admin_user_id);
CREATE INDEX ix_admin_refresh_token_expires ON admin_refresh_token (expires_at);


-- 로그인 시도 기록.
-- 계정 전면 잠금만 두면 공격자가 아무 비밀번호나 반복해 대표님을
-- 상시 차단할 수 있다(가용성 DoS). IP 기준을 1차 방어로 삼는다.
CREATE TABLE login_attempt (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username     VARCHAR(60)  NOT NULL,
    ip           INET         NOT NULL,
    successful   BOOLEAN      NOT NULL,
    user_agent   VARCHAR(400),
    attempted_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX ix_login_attempt_ip   ON login_attempt (ip, attempted_at DESC);
CREATE INDEX ix_login_attempt_user ON login_attempt (username, attempted_at DESC);


-- ───────────────────────────────────────────────────────────────
--  감사 로그
--
--  사고가 났을 때 유일한 단서다 (기획서 §13).
--  개인정보 조회·CSV 내보내기도 반드시 여기에 남긴다 —
--  컬럼 암호화를 무력화하는 통로가 CSV 내보내기이기 때문이다.
-- ───────────────────────────────────────────────────────────────
CREATE TABLE admin_audit_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_user_id BIGINT,
    -- 계정이 지워져도 로그는 남아야 하므로 이름을 문자열로 함께 박아둔다
    admin_username VARCHAR(60) NOT NULL DEFAULT '',
    action        VARCHAR(60)  NOT NULL,
    target_type   VARCHAR(40),
    target_id     VARCHAR(60),
    -- 변경 요약. ★ 여기에 비밀번호·토큰·전화번호 평문을 넣지 말 것.
    detail        TEXT         NOT NULL DEFAULT '',
    ip            INET,
    user_agent    VARCHAR(400),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_admin_audit_log_user
        FOREIGN KEY (admin_user_id) REFERENCES admin_user (id) ON DELETE SET NULL
);

CREATE INDEX ix_admin_audit_log_created ON admin_audit_log (created_at DESC);
CREATE INDEX ix_admin_audit_log_action  ON admin_audit_log (action, created_at DESC);

COMMENT ON TABLE admin_audit_log IS '보관 기간 최소 3개월. 개인정보 조회·내보내기도 기록한다.';
