CREATE TABLE news (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug          VARCHAR(140) NOT NULL,
    title         VARCHAR(200) NOT NULL,
    -- ★ 살균된 HTML 만.
    body          TEXT         NOT NULL DEFAULT '',
    thumbnail_key VARCHAR(255),
    published_at  TIMESTAMPTZ,
    visible       BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_news_slug UNIQUE (slug),
    -- 공개하려면 발행일이 반드시 있어야 한다
    CONSTRAINT ck_news_published CHECK (NOT visible OR published_at IS NOT NULL)
);

CREATE INDEX ix_news_published ON news (published_at DESC) WHERE visible;


-- ───────────────────────────────────────────────────────────────
--  문의  ★ 개인정보를 담는 유일한 테이블
--
--  이 테이블 하나가 이 시스템에서 가장 위험한 자산이다 (기획서 §7).
--  유출 시 외부의 불법적 접근에 의한 것이면 건수와 무관하게
--  72시간 내 신고 의무가 발생한다.
-- ───────────────────────────────────────────────────────────────
CREATE TABLE inquiry (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    type              VARCHAR(20)  NOT NULL,

    name              VARCHAR(80)  NOT NULL,

    -- ★ AES-256-GCM 암호문(base64). 평문 전화번호를 여기 넣지 말 것.
    --   DB 가 통째로 유출돼도 즉시 악용되지 않게 하는 마지막 방어선이다.
    phone_encrypted   TEXT         NOT NULL,

    -- ★ 검색용 블라인드 인덱스.
    --   정규화한 번호(숫자만)의 HMAC-SHA256. 복호화가 불가능하면서
    --   "같은 번호인가"는 판별된다. 결정적 암호화를 쓰면 안 되는 이유는
    --   같은 평문이 같은 암호문이 되어 빈도 분석이 가능해지기 때문이다.
    phone_blind_index BYTEA,

    email             VARCHAR(160),
    company           VARCHAR(120),
    region            VARCHAR(60),
    message           TEXT         NOT NULL DEFAULT '',

    status            VARCHAR(20)  NOT NULL DEFAULT 'NEW',
    -- 관리자 내부 메모. 정보주체 열람 청구 대상이 될 수 있으므로
    -- 주관적 평가를 적지 않도록 관리 화면에 안내를 띄운다.
    memo              TEXT         NOT NULL DEFAULT '',

    -- ── 법적 요건 (기획서 §14) ──
    -- 수집·이용 동의 시각. NULL 이면 애초에 저장돼선 안 된다.
    consent_at        TIMESTAMPTZ  NOT NULL,
    -- 마케팅 활용 동의는 반드시 별도 항목이다. 선택이므로 NULL 허용.
    marketing_consent_at TIMESTAMPTZ,
    -- 보유기간 만료 시각. 배치가 이 값을 지난 행을 파기한다.
    purge_at          TIMESTAMPTZ  NOT NULL,

    -- 스팸 분석용. 개인정보이므로 파기 대상에 함께 포함된다.
    source_ip         INET,
    user_agent        VARCHAR(400),

    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_inquiry_type   CHECK (type IN ('QUOTE', 'DEMO', 'OFFICIAL', 'ETC')),
    CONSTRAINT ck_inquiry_status CHECK (status IN ('NEW', 'CONTACTING', 'DONE', 'SPAM')),
    CONSTRAINT ck_inquiry_purge  CHECK (purge_at > consent_at)
);

COMMENT ON TABLE  inquiry                   IS '개인정보 포함. 접근 권한 최소화 + 조회 이력 로깅 대상.';
COMMENT ON COLUMN inquiry.phone_encrypted   IS 'AES-256-GCM(base64). 평문 금지.';
COMMENT ON COLUMN inquiry.phone_blind_index IS 'HMAC-SHA256(정규화 번호). 검색 전용.';
COMMENT ON COLUMN inquiry.purge_at          IS '자동 파기 기준 시각. 배치가 매일 확인한다.';

-- 관리 화면 기본 목록: 상태별 최신순
CREATE INDEX ix_inquiry_status_created ON inquiry (status, created_at DESC);
-- 전화번호 검색
CREATE INDEX ix_inquiry_phone_blind    ON inquiry (phone_blind_index);
-- 파기 배치가 매일 스캔한다. 부분 인덱스로 대상만 좁힌다.
CREATE INDEX ix_inquiry_purge          ON inquiry (purge_at);


-- 문의 ↔ 제품 (docs/OPEN-DECISIONS.md D-4)
-- 단일 컬럼에 ID 목록을 넣지 않는다. "어떤 제품 문의가 많은가"는
-- 기획서 §1.2 의 2차 KPI 이므로 반드시 집계하게 된다.
CREATE TABLE inquiry_product (
    inquiry_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,

    PRIMARY KEY (inquiry_id, product_id),
    CONSTRAINT fk_inquiry_product_inquiry
        FOREIGN KEY (inquiry_id) REFERENCES inquiry (id) ON DELETE CASCADE,
    -- 제품이 지워져도 문의 기록은 남아야 하지만, 어떤 제품이었는지는
    -- 알 수 없게 된다. 제품은 삭제 대신 visible=FALSE 로 운영한다.
    CONSTRAINT fk_inquiry_product_product
        FOREIGN KEY (product_id) REFERENCES product (id) ON DELETE CASCADE
);

CREATE INDEX ix_inquiry_product_product ON inquiry_product (product_id);


