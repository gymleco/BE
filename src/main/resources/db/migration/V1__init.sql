-- ═══════════════════════════════════════════════════════════════
--  V1 — 초기 스키마
--
--  설계 원칙
--   1. 스키마의 소유자는 Flyway 다. Hibernate 는 validate 만 한다.
--   2. 개인정보는 최소 수집 + 암호화 + 만료 파기. 컬럼 단위로 명시한다.
--   3. 열거값은 TEXT + CHECK 로 둔다. DB 열거형은 값 추가가 번거롭고,
--      정수 코드는 DB 를 직접 볼 때 의미를 알 수 없다.
--   4. 모든 시각은 TIMESTAMPTZ. 서버 타임존이 바뀌어도 값이 흔들리지 않는다.
-- ═══════════════════════════════════════════════════════════════


-- ───────────────────────────────────────────────────────────────
--  제품
-- ───────────────────────────────────────────────────────────────
CREATE TABLE product (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- URL 에 노출된다. 한번 공개되면 바꾸기 어려우므로 불변으로 취급한다.
    slug            VARCHAR(120)  NOT NULL,
    name_ko         VARCHAR(120)  NOT NULL,
    name_en         VARCHAR(120)  NOT NULL,
    category        VARCHAR(20)   NOT NULL,

    -- 쇼케이스에서 제품명 아래 한 줄로 붙는다
    summary         VARCHAR(200)  NOT NULL DEFAULT '',
    -- 리치 텍스트. ★ 저장 시점에 살균된 HTML 만 들어와야 한다 (기획서 §11).
    description     TEXT          NOT NULL DEFAULT '',

    -- 치수. 설치 면적은 이 사이트의 핵심 소구점이라 NULL 을 허용하지 않는다.
    footprint_m2    NUMERIC(6, 2) NOT NULL,
    width_mm        INTEGER       NOT NULL,
    depth_mm        INTEGER       NOT NULL,
    height_mm       INTEGER       NOT NULL,
    weight_kg       NUMERIC(7, 2) NOT NULL,

    thumbnail_key   VARCHAR(255),
    sort_order      INTEGER       NOT NULL DEFAULT 0,
    visible         BOOLEAN       NOT NULL DEFAULT FALSE,

    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT uq_product_slug        UNIQUE (slug),
    CONSTRAINT ck_product_category    CHECK (category IN ('STRENGTH', 'CABLE', 'RACK', 'BENCH', 'CARDIO')),
    CONSTRAINT ck_product_slug_format CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT ck_product_dimensions  CHECK (
        footprint_m2 > 0 AND width_mm > 0 AND depth_mm > 0 AND height_mm > 0 AND weight_kg > 0
    )
);

COMMENT ON COLUMN product.description IS '살균된 HTML 만 저장한다. 원문을 그대로 넣지 말 것.';
COMMENT ON COLUMN product.visible     IS '기본 FALSE. 실수로 미완성 제품이 공개되지 않게 한다.';

-- 공개 목록 조회는 항상 visible=TRUE + sort_order 정렬이다.
CREATE INDEX ix_product_visible_sort ON product (sort_order, id) WHERE visible;


CREATE TABLE product_image (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   BIGINT       NOT NULL,
    image_key    VARCHAR(255) NOT NULL,
    alt_text     VARCHAR(200) NOT NULL DEFAULT '',
    sort_order   INTEGER      NOT NULL DEFAULT 0,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_product_image_product
        FOREIGN KEY (product_id) REFERENCES product (id) ON DELETE CASCADE
);

CREATE INDEX ix_product_image_product ON product_image (product_id, sort_order);


-- ───────────────────────────────────────────────────────────────
--  소식
